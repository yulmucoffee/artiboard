test('JS: functions declared one level inside a top-level function are its own symbols; deeper ones are not', () => {
  const r = jsLang.extract(FACTORY, 'shop.js');
  assert.deepEqual(r.symbols, [sym('makeShop', 'fn', 1, 15, true), sym('makeShop.load', 'fn', 3, 5, true), sym('makeShop.save', 'fn', 6, 9, true),
    sym('makeShop.check', 'fn', 10, 13, true), sym('wrap', 'fn', 16, 19, true), sym('wrap.inner', 'fn', 17, 17, true)], 'deep is two levels in');
  const b = buildGraph(new Map([['shop.js', FACTORY], ['use.js', "import { makeShop } from './shop.js';\nconst shop = makeShop(db);\nshop.save(1);\n"]]), {});
  assert.deepEqual(allEdges(b).filter((e) => e[2] === 'calls'), [
    ['shop.js#makeShop.save', 'shop.js#makeShop.check', 'calls', 'x'],
    ['shop.js#makeShop.save', 'shop.js#makeShop.load', 'calls', 'x'],
    ['shop.js#wrap', 'shop.js#wrap.inner', 'calls', 'x'],
    ['shop.js#wrap.inner', 'shop.js#makeShop', 'calls', 'x'],
    ['use.js#shop', 'shop.js#makeShop', 'calls', 'x'],
  ], 'a call inside save is save\'s; item.load( and shop.save( are some object\'s, not the nested functions of those names');
  assert.deepEqual(allEdges(b).filter((e) => e[2] === 'uses'), [
    ['shop.js#makeShop', 'shop.js#makeShop.load', 'uses', 'x'],
    ['shop.js#makeShop', 'shop.js#makeShop.save', 'uses', 'x'],
  ], 'makeShop hands out load and save');
  const g = loadGraph(...Object.values(buildGraph(new Map([['shop.js', FACTORY], ['other.js', 'export function save() {}\n']]), {})));
  assert.equal(g.explain('load').id, 'shop.js#makeShop.load', 'a nested function by its own name');
  assert.deepEqual(g.explain('save').ambiguous, ['other.js#save', 'shop.js#makeShop.save'], 'as much a function named save as other.js\'s');
});

