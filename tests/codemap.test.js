test('build: chunks keep under chunkBytes, nodes in id order, each edge with its from node', () => {
  const check = (b, limit) => {
    const ids = allNodes(b).map((n) => n.i);
    assert.deepEqual(ids, ids.slice().sort(), 'nodes in id order across chunks');
    for (const ch of b.chunks) {
      assert.ok(Buffer.byteLength(JSON.stringify(ch)) <= limit, `a chunk of ${Buffer.byteLength(JSON.stringify(ch))} bytes`);
    }
    assert.equal(b.index.chunks, b.chunks.length);
    assert.equal(allEdges(b).length, b.index.counts.edges);
  };
  const small = buildGraph(new Map(readShop()), { repo: 'acme/shop', chunkBytes: 3000 });
  check(small, 3000);
  assert.ok(small.chunks.length >= 4, `${small.chunks.length} chunks`);
  for (const ch of small.chunks) {
    const here = new Set(ch.nodes.map((n) => n.i));
    assert.ok(ch.edges.every((e) => here.has(e[0])), 'edges with their from node');
  }
  assert.deepEqual(allEdges(small), allEdges(built), 'the same edges as in one chunk');
  const g = loadGraph(small.index, small.chunks);
  assert.deepEqual(g.explain('Cart').lines, G.explain('Cart').lines);

  // 40 files of 15 functions, each calling the next file's: about 150 KB of map
  const files = new Map();
  for (let f = 0; f < 40; f++) {
    const body = [`import { f${(f + 1) % 40}_0 } from './m${(f + 1) % 40}.js';`];
    for (let k = 0; k < 15; k++) body.push(`export function f${f}_${k}() { return f${(f + 1) % 40}_0() + ${k}; }`);
    files.set(`lib/m${f}.js`, `${body.join('\n')}\n`);
  }
  const big = buildGraph(files, { repo: 'acme/big', chunkBytes: 20000 });
  check(big, 20000);
  assert.ok(big.chunks.length >= 5, `${big.chunks.length} chunks`);
  assert.equal(big.index.counts.symbols, 600);

  // one file defining 400 functions: its edges alone overflow a chunk, so they spill into the next
  const wide = buildGraph(new Map([['wide.js', Array.from({ length: 400 }, (_, k) => `export function wideFunction${k}() {}`).join('\n')]]), { chunkBytes: 20000 });
  check(wide, 20000);
  assert.ok(wide.chunks.length >= 2);
  assert.equal(allEdges(wide).length, 400);
});

