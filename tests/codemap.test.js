test('overlaps and path lookups stay fast on a big map: touches are read once, and a path is found by its end', () => {
  // 5,000 files of 9 symbols, each importing the next; 210 open tasks of 8 touches, some of them paths not in the map
  const nodes = [], edges = [];
  for (let f = 0; f < 5000; f++) {
    const p = `pkg${f % 50}/mod${f}.js`;
    nodes.push({ i: p, k: 'file', n: `mod${f}.js`, f: p, l: 0 });
    for (let k = 0; k < 9; k++) { nodes.push({ i: `${p}#fn${k}`, k: 'sym', n: `fn${k}`, f: p, l: k + 1, t: 'fn' }); edges.push([p, `${p}#fn${k}`, 'defines', 'x']); }
    edges.push([p, `pkg${(f + 1) % 50}/mod${(f + 1) % 5000}.js`, 'imports', 'x']);
  }
  const g = loadGraph({}, [{ nodes, edges }]);
  const tasks = Array.from({ length: 210 }, (_, t) => ({
    key: `T-${t}`, holder: `p${t % 30}`,
    touches: Array.from({ length: 8 }, (_, k) => [`pkg${(t * 8 + k) % 50}/mod${(t * 37 + k * 11) % 5000}.js`,
      `pkg${k}/mod${t * 8 + k}.js#fn${k % 9}`, `gone/old${t}_${k}.js`, `name${(t + k) % 40}`][k % 4]),
  }));
  const start = performance.now();
  const o = g.overlaps(tasks);
  for (const t of tasks) for (const touch of t.touches) g.file(touch);
  const ms = performance.now() - start;
  assert.ok(o.pairs.length > 0);
  assert.ok(ms < 1000, `${ms.toFixed(0)} ms`);
  assert.equal(g.file('pkg7/mod7.js').id, 'pkg7/mod7.js');
  assert.equal(g.file('mod7.js').id, 'pkg7/mod7.js', 'by its name');
  assert.equal(g.file('a/pkg7/mod7.js').missing, true, 'a longer path is not this one');
  assert.equal(g.file('kg7/mod7.js').missing, true, 'an end must start at a folder');
  assert.equal(G.file('util/format.js').id, 'src/util/format.js', 'a path by its end');
  assert.equal(G.file('codemap/src/util/format.js').missing, true);
});

